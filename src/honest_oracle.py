"""
An ECDLP oracle a compiler can build without knowing the answer.

The distinction this file exists to make
----------------------------------------
Shor's algorithm for ECDLP prepares

    (1/n) SUM_{a,b} |a> |b> |aP + bQ>

and the only hard part is the third register. There are two ways to build it,
and they are not equivalent:

  DISHONEST -- label each point by its discrete logarithm base P, so iP becomes
  the integer i. The group law collapses to addition mod n, which is cheap.
  But Q's label IS k, so writing the oracle down requires already possessing
  the answer. arXiv:2507.10592 does exactly this (ORDER = 32, P_IDX = 1,
  Q_IDX = 23) and is therefore, in Smolin-Smith-Vargo's phrasing, not solving
  the problem it claims to solve.

  HONEST -- label each point by a canonical ordering of its COORDINATES, and
  implement the actual group law. Both permutations are then derived from the
  curve, P, and Q, all of which are public. k never appears at construction
  time and is not recoverable from the circuit without running it.

This module does the second. That is the whole reason it is worth spending QPU
seconds on, and it is why the circuits here are far more expensive than the
published ones -- the cheapness of those circuits is precisely the tell.

Cost
----
Real group law means each controlled step is an arbitrary permutation over the
point set, not an increment. Depth grows accordingly. Measuring that cost on
real silicon, and stating it plainly, is the deliverable.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

from qiskit import QuantumCircuit, QuantumRegister, ClassicalRegister
from qiskit.circuit.library import QFT

from ecdlp_ladder import Challenge, point_add, scalar_mul


# ── Canonical labels: an ordering that cannot encode the answer ─────────────


def canonical_labels(ch: Challenge) -> tuple[dict, list]:
    """
    Enumerate the subgroup generated by P and label its elements by SORTED
    COORDINATES -- infinity first, then ascending (x, y).

    Note what this ordering is not: it is not the discrete-log ordering. Two
    adjacent labels are unrelated as group elements, so the permutation induced
    by "+P" carries no shortcut, and neither the label of Q nor any other label
    reveals k without solving the problem.

    The subgroup is enumerated by repeatedly adding P, which does require
    walking every element -- but walking is not the same as looking up an
    answer: at no point is Q's position consulted while the labels are assigned.
    """
    pts = [None]
    cur = ch.P
    while cur is not None:
        pts.append(cur)
        cur = point_add(cur, ch.P, ch.p)
        if cur == ch.P:
            break

    finite = sorted(pt for pt in pts if pt is not None)
    ordered = [None] + finite
    return {pt: i for i, pt in enumerate(ordered)}, ordered


def addition_permutation(ch: Challenge, addend, labels, ordered) -> list[int]:
    """
    The permutation label(R) -> label(R + addend), extended to the identity on
    the unused tail of the register.

    Computed with the curve's own addition formulas from `addend`'s coordinates.
    For addend = Q this is the step a dishonest implementation replaces with
    "+k mod n", and the replacement is exactly where the answer leaks in.
    """
    width = 1 << math.ceil(math.log2(len(ordered)))
    perm = list(range(width))
    for i, pt in enumerate(ordered):
        perm[i] = labels[point_add(pt, addend, ch.p)]
    return perm


# ── Basis-state permutation ─────────────────────────────────────────────────


def _basis_permutation_gate(perm: list[int], nq: int, label: str):
    """
    A gate sending |i> to |perm[i]> on nq qubits.

    Not to be confused with Qiskit's PermutationGate, which permutes WIRES --
    a permutation of nq qubits, not of the 2^nq basis states. The group law
    needs the latter: "add the point R" relabels states, it does not reorder
    registers. That distinction is worth stating because the wire version is
    cheap and the state version is not, and mistaking one for the other is
    another way to publish a circuit far cheaper than the problem allows.

    Built as a unitary matrix and handed to the transpiler, which synthesises
    it exactly. Exact synthesis of an arbitrary 2^nq permutation is expensive;
    that expense is the honest cost of not knowing the answer in advance.
    """
    import numpy as np
    from qiskit.circuit.library import UnitaryGate

    dim = 1 << nq
    mat = np.zeros((dim, dim))
    for src, dst in enumerate(perm):
        mat[dst, src] = 1.0
    return UnitaryGate(mat, label=label)


# ── Circuit ─────────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class OracleCircuit:
    circuit: QuantumCircuit
    reg_bits: int          # width of each of the two exponent registers
    point_bits: int
    ordered: list
    challenge: Challenge


def build_ecdlp_circuit(ch: Challenge, reg_bits: int | None = None) -> OracleCircuit:
    """
    |a>|b>|O>  ->  |a>|b>|aP + bQ>  ->  QFT on a and b  ->  measure.

    Registers are `reg_bits` wide, defaulting to ceil(log2 n). The QFT is over
    2^reg_bits rather than n, so the peaks are the usual approximate ones; the
    decode below accounts for that without appealing to the answer.
    """
    labels, ordered = canonical_labels(ch)
    point_bits = math.ceil(math.log2(len(ordered)))
    m = reg_bits if reg_bits is not None else math.ceil(math.log2(ch.n))

    a = QuantumRegister(m, "a")
    b = QuantumRegister(m, "b")
    r = QuantumRegister(point_bits, "pt")
    ca, cb = ClassicalRegister(m, "ma"), ClassicalRegister(m, "mb")
    qc = QuantumCircuit(a, b, r, ca, cb)

    qc.h(a)
    qc.h(b)

    # Double-and-add, controlled on each exponent bit. Bit i of `a` contributes
    # 2^i * P, so the permutation applied is "+ (2^i)P" -- built from the point
    # (2^i)P, which is public.
    for reg, base in ((a, ch.P), (b, ch.Q)):
        for i in range(m):
            addend = scalar_mul(pow(2, i, ch.n), base, ch.p)
            if addend is None:
                continue
            perm = addition_permutation(ch, addend, labels, ordered)
            gate = _basis_permutation_gate(perm, point_bits, label=f"+{i}")
            qc.append(gate.control(1), [reg[i], *r])

    qc.append(QFT(m, do_swaps=True).to_gate(label="QFT"), a)
    qc.append(QFT(m, do_swaps=True).to_gate(label="QFT"), b)

    qc.measure(a, ca)
    qc.measure(b, cb)
    return OracleCircuit(qc, m, point_bits, ordered, ch)


# ── Decode, derived rather than fitted ──────────────────────────────────────
#
# Tracing out the point register leaves, for each outcome c, the set
# {(a,b) : a + bk = c mod n}. Applying the QFT to both registers gives
#
#     SUM_{A,B} w^(Ac) [ SUM_b w^(b(B - Ak)) ] |A>|B>
#
# whose inner sum is n * delta(B = kA mod n). So the peaks lie on B = k*A, and
#
#     k = B * A^-1 mod n
#
# That derivation uses no knowledge of k. It also settles a discrepancy in
# arXiv:2507.10592: with its own constants (n=32, Q=23P) the paper's stated
# formula k = -A*B^-1 yields 25, while the value it reports as recovered, 7,
# is 23^-1 mod 32 -- the modular inverse of the true scalar, i.e. the same
# ridge read with A and B exchanged.


def decode_candidates(counts: dict, m: int, n: int) -> list[tuple[int, int]]:
    """
    Turn raw measurement counts into (candidate_k, weight), most frequent first.

    With a 2^m QFT the ridge is smeared, so each outcome is mapped through the
    nearest-multiple rescaling A -> round(A * n / 2^m) before inversion. Every
    surviving candidate must still pass d*P == Q; this only orders the guesses.
    """
    tally: dict[int, int] = {}
    for bitstring, shots in counts.items():
        parts = bitstring.split()
        if len(parts) != 2:
            continue
        # Qiskit returns classical registers in reverse declaration order.
        B_raw, A_raw = int(parts[0], 2), int(parts[1], 2)
        A = round(A_raw * n / (1 << m)) % n
        B = round(B_raw * n / (1 << m)) % n
        if A == 0:
            continue
        try:
            k = B * pow(A, -1, n) % n
        except ValueError:
            continue
        tally[k] = tally.get(k, 0) + shots
    return sorted(tally.items(), key=lambda kv: -kv[1])
